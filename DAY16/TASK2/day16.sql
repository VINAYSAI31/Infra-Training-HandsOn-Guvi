CREATE DATABASE MI_MATCHES;

CREATE SCHEMA CRICKET;

SHOW DATABASES LIKE 'MI_MATCHES';

CREATE WAREHOUSE IF NOT EXISTS MI_COMPUTE_WH
	WAREHOUSE_SIZE = 'XSMALL'
	AUTO_SUSPEND = 60
	AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;


CREATE OR REPLACE FILE FORMAT MI_PLAYERS_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE FILE FORMAT MI_MATCHES_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA MI_MATCHES.CRICKET;


CREATE TABLE MI_PLAYERS (
    PLAYER_ID NUMBER,
    PLAYER_NAME VARCHAR(100),
    ROLE VARCHAR(50),
    COUNTRY VARCHAR(50),
    BASE_PRICE NUMBER(15,2)
);

CREATE TABLE MI_MATCHES (
    MATCH_ID NUMBER,
    OPPONENT VARCHAR(50),
    VENUE VARCHAR(100),
    MATCH_DATE DATE,
    MI_SCORE NUMBER,
    OPPONENT_SCORE NUMBER,
    RESULT VARCHAR(20),
    PLAYER_OF_MATCH VARCHAR(100)
);

SHOW TABLES;


CREATE STAGE MI_MATCHES_STAGE
FILE_FORMAT=MI_MATCHES_FORMAT;

CREATE STAGE MI_PLAYERS_STAGE
FILE_FORMAT=MI_PLAYERS_FORMAT;

SHOW STAGES;

//add csv files into stages 


//LIST THE FILES
LIST @MI_MATCHES.CRICKET.MI_PLAYERS_STAGE;

LIST @MI_MATCHES.CRICKET.MI_MATCHES_STAGE;

//copy the data into tables
COPY INTO MI_MATCHES.CRICKET.MI_MATCHES
FROM @MI_MATCHES.CRICKET.MI_MATCHES_STAGE
FILE_FORMAT=(FORMAT_NAME='MI_MATCHES.CRICKET.MI_MATCHES_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';


COPY INTO MI_MATCHES.CRICKET.MI_PLAYERS
FROM @MI_MATCHES.CRICKET.MI_PLAYERS_STAGE
FILE_FORMAT=(FORMAT_NAME='MI_MATCHES.CRICKET.MI_PLAYERS_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT PLAYER_ID, COUNT(*)
FROM MI_PLAYERS
GROUP BY PLAYER_ID
HAVING COUNT(*) > 1;

SELECT MATCH_ID, COUNT(*)
FROM MI_MATCHES
GROUP BY MATCH_ID
HAVING COUNT(*) > 1;

SELECT *
FROM MI_MATCHES
WHERE MATCH_ID IS NULL
   OR OPPONENT IS NULL
   OR RESULT IS NULL;
SELECT
    PLAYER_ID,
    COALESCE(TRIM(PLAYER_NAME), 'Unknown')
        AS PLAYER_NAME,
    UPPER(TRIM(ROLE)) AS PLAYER_ROLE,
    UPPER(TRIM(COUNTRY)) AS COUNTRY,
    BASE_PRICE
FROM MI_PLAYERS;

SELECT
    MATCH_ID,
    UPPER(TRIM(OPPONENT)) AS OPPONENT,
    TRIM(VENUE) AS VENUE,
    MATCH_DATE,
    MI_SCORE,
    OPPONENT_SCORE,
    UPPER(TRIM(RESULT)) AS RESULT,
    COALESCE(PLAYER_OF_MATCH, 'Unknown')
        AS PLAYER_OF_MATCH
FROM MI_MATCHES;

SELECT * FROM MI_PLAYERS;

SELECT *
FROM MI_PLAYERS
WHERE COUNTRY = 'India';

SELECT *
FROM MI_PLAYERS
WHERE UPPER(ROLE) = 'BATSMAN';

SELECT *
FROM MI_PLAYERS
ORDER BY BASE_PRICE DESC
LIMIT 1;

SELECT *
FROM MI_MATCHES
WHERE VENUE = 'Wankhede Stadium';


SELECT MAX(MI_SCORE) AS HIGHEST_SCORE
FROM MI_MATCHES;

SELECT
    P.PLAYER_ID,
    P.PLAYER_NAME,
    P.ROLE,
    M.OPPONENT,
    M.MATCH_DATE,
    M.RESULT
FROM MI_PLAYERS P
INNER JOIN MI_MATCHES M
    ON P.PLAYER_NAME = M.PLAYER_OF_MATCH;


SELECT
    P.PLAYER_NAME,
    P.ROLE,
    COUNT(M.MATCH_ID) AS AWARD_COUNT
FROM MI_PLAYERS P
LEFT JOIN MI_MATCHES M
    ON P.PLAYER_NAME = M.PLAYER_OF_MATCH
GROUP BY P.PLAYER_NAME, P.ROLE
ORDER BY AWARD_COUNT DESC;

SELECT *
FROM (
    SELECT *
    FROM MI_MATCHES
) M
WHERE M.RESULT = 'WON';

SELECT
    MATCH_ID,
    OPPONENT,
    VENUE,
    MI_SCORE,
    RESULT
FROM MI_MATCHES
WHERE RESULT = 'WON';

