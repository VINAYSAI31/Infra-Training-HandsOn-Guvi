CREATE DATABASE IF NOT EXISTS IPL_DB;

SHOW DATABASES LIKE 'IPL_DB';

CREATE SCHEMA IF NOT EXISTS IPL;

USE SCHEMA IPL_DB.IPL;

SHOW SCHEMAS IN DATABASE IPL_DB;


CREATE WAREHOUSE IF NOT EXISTS IPL_WH
	WAREHOUSE_SIZE = 'XSMALL'
	AUTO_SUSPEND = 60
	AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE IPL_WH;


SELECT CURRENT_WAREHOUSE();
CREATE TABLE IF NOT EXISTS IPL_DB.IPL.IPL_DATA (
    MATCH_ID VARCHAR(50),
    TEAM VARCHAR(100),
    OPPONENT VARCHAR(100),
    SEASON VARCHAR(50),
    MATCHES_PLAYED VARCHAR(50),
    WINS VARCHAR(50),
    LOSSES VARCHAR(50),
    RUN_RATE VARCHAR(50),
    POINTS VARCHAR(50),
    VENUE VARCHAR(100)
);

SHOW TABLES LIKE 'IPL_DATA' IN SCHEMA IPL_DB.IPL;

DESCRIBE TABLE IPL_DB.IPL.IPL_DATA;

CREATE FILE FORMAT IPL_DB.IPL.IPL_CSV_FORMAT
TYPE = 'CSV'
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA IPL_DB.IPL;

CREATE STAGE IF NOT EXISTS IPL_STAGE
FILE_FORMAT = IPL_CSV_FORMAT;

LIST @IPL_DB.IPL.IPL_STAGE;

COPY INTO IPL_DB.IPL.IPL_DATA
FROM @IPL_DB.IPL.IPL_STAGE
FILE_FORMAT = (FORMAT_NAME = 'IPL_DB.IPL.IPL_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_RECORDS
FROM IPL_DB.IPL.IPL_DATA;

SELECT * FROM IPL_DB.IPL.IPL_DATA
ORDER BY WINS;

DROP DATABASE IPL_DB;

DROP WAREHOUSE IF EXISTS IPL_WH;






















    





